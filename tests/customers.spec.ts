import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
import { randomInt } from 'node:crypto';

test('admin registers, finds and inspects a customer on desktop and mobile', async ({ page }, testInfo) => {
  const credentials = JSON.parse(readFileSync('.local/e2e-admin.json', 'utf8'));
  await page.goto('/admin');
  await page.getByLabel('Correo electrónico', { exact: true }).fill(credentials.email);
  await page.getByLabel('Contraseña de Acceso').fill(credentials.password);
  await page.getByRole('button', { name: 'Iniciar Sesión', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Dashboard General' })).toBeVisible();
  await page.goto('/admin/clientes');
  await expect(page.getByRole('heading', { name: 'Listado general' })).toBeVisible();
  await page.getByRole('button', { name: 'Registrar cliente', exact: true }).click();
  const dialog = page.getByRole('dialog');
  const email = `admin-${Date.now()}-${testInfo.project.name}@e2e.example.test`;
  await dialog.getByLabel('Nombre completo').fill('Cliente E2E Admin');
  await dialog.getByLabel('Correo electrónico').fill(email);
  await dialog.getByLabel('Celular', { exact: true }).fill(`9${randomInt(10000000, 99999999)}`);
  await dialog.getByLabel('Confirmo que el cliente autorizó').check();
  await dialog.getByRole('button', { name: 'Guardar cliente' }).click();
  await expect(dialog).not.toBeVisible();
  await expect(page.getByRole('status').filter({ hasText: 'Cliente registrado correctamente.' })).toBeVisible();
  await page.getByLabel('Buscar clientes').fill(email);
  await expect(page.getByRole('cell', { name: email, exact: false })).toBeVisible();
  await expect(page.getByText('Mostrando 1 de 1', { exact: true })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('clientes.png'), fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.getByRole('button', { name: 'Ver historial de Cliente E2E Admin' }).click();
  await expect(dialog.getByRole('heading', { name: 'Historial de canjes' })).toBeVisible();
  await expect(dialog.getByText('Registrado por el administrador')).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('historial.png'), fullPage: true });
  await page.keyboard.press('Escape');
  await expect(dialog).not.toBeVisible();
  await page.getByRole('button', { name: 'Editar cliente Cliente E2E Admin', exact: true }).click();
  await dialog.getByLabel('Nombre completo').fill('Cliente E2E Editado');
  await dialog.getByRole('button', { name: 'Guardar cliente' }).click();
  await expect(dialog).not.toBeVisible();
  await expect(page.getByRole('rowheader', { name: 'Cliente E2E Editado', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Eliminar cliente Cliente E2E Editado', exact: true }).click();
  await dialog.getByRole('button', { name: 'Cancelar', exact: true }).click();
  await expect(page.getByRole('rowheader', { name: 'Cliente E2E Editado', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Eliminar cliente Cliente E2E Editado', exact: true }).click();
  await dialog.getByRole('button', { name: 'Confirmar eliminación' }).click();
  await expect(dialog).not.toBeVisible();
  await expect(page.getByRole('heading', { name: 'No hay clientes para mostrar' })).toBeVisible();
  await page.getByRole('button', { name: /^Frecuentes/ }).click();
  await expect(page.getByRole('heading', { name: 'No hay clientes para mostrar' })).toBeVisible();
});
