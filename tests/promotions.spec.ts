import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
import { randomInt } from 'node:crypto';

test('promotion creation, email preview, local processing, unsubscribe and scheduling', async ({ page }, testInfo) => {
  const credentials = JSON.parse(readFileSync('.local/e2e-admin.json', 'utf8'));
  const unique = `${Date.now()}-${testInfo.project.name}`, name = `Promoción E2E ${unique}`;
  await page.goto('/admin');
  await page.getByLabel('Correo electrónico', { exact: true }).fill(credentials.email);
  await page.getByLabel('Contraseña de Acceso').fill(credentials.password);
  await page.getByRole('button', { name: 'Iniciar Sesión', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Dashboard General' })).toBeVisible();
  // Public registration provides the real recipient for the local campaign.
  const email = `promotion-${unique}@e2e.example.test`;
  const registration = await page.request.post('/api/v1/public/customers', { headers: { Origin: 'http://localhost:5174' }, data: { name: 'Cliente E2E', email, phone: `9${randomInt(10000000,99999999)}`, consent: true } });
  expect(registration.status()).toBe(201);
  await page.goto('/admin/promociones');
  await expect(page.getByText('Modo de pruebas:', { exact: false })).toHaveCount(0);
  await page.getByRole('button', { name: 'Nueva promoción', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByLabel('Nombre de la promoción', { exact: true }).fill(name);
  await dialog.getByLabel('Beneficio o descuento').fill('20% en pachamanca');
  await dialog.getByLabel('Código compartido').fill(`E2E-${unique}`);
  await dialog.getByLabel('Condiciones', { exact: true }).fill('Una promoción por cliente. Válida para consumo en el local.');
  await dialog.getByLabel('Imagen de la promoción', { exact: true }).setInputFiles('frontend/public/assets/figma/c4c0d.png');
  await expect(dialog.getByRole('img', { name: 'Imagen de la promoción', exact: true })).toBeVisible();
  const local = (ms: number) => new Date(ms - 5 * 3600000).toISOString().slice(0,16);
  await dialog.getByLabel('Inicio de vigencia').fill(local(Date.now() - 86400000));
  await dialog.getByLabel('Fin de vigencia').fill(local(Date.now() + 7 * 86400000));
  await dialog.getByLabel('Limitar el total de canjes').check();
  await dialog.getByLabel('Límite total de canjes',{exact:true}).fill('200');
  await page.screenshot({ path: testInfo.outputPath('formulario-promocion.png'), fullPage: true });
  await dialog.getByRole('button', { name: 'Guardar promoción' }).click();
  await expect(dialog).not.toBeVisible();
  await expect(page.getByRole('status').filter({hasText:'Promoción creada'})).toBeVisible();
  await page.getByRole('button',{name:'Cerrar aviso'}).click();
  await expect(page.getByRole('button',{name:'Cerrar aviso'})).toHaveCount(0);
  await page.getByLabel('Buscar promociones').fill(unique);
  const card = page.getByRole('article').filter({ has: page.getByRole('heading', { name, exact: true }) });
  await expect(card).toBeVisible();
  await expect(card).toContainText('0 de 200 canjes · 200 disponibles');
  await card.getByRole('button',{name:'Editar',exact:true}).click();
  await expect(dialog.getByLabel('Limitar el total de canjes')).toBeChecked();
  await expect(dialog.getByLabel('Límite total de canjes',{exact:true})).toHaveValue('200');
  await dialog.getByLabel('Limitar el total de canjes').uncheck();
  await expect(dialog.getByLabel('Límite total de canjes',{exact:true})).toHaveCount(0);
  await dialog.getByRole('button',{name:'Guardar promoción'}).click();
  await expect(dialog).not.toBeVisible();
  await expect(card).toContainText('Sin límite total');
  await expect.poll(() => page.locator('img').evaluateAll(images => images.every(img => (img as HTMLImageElement).complete && (img as HTMLImageElement).naturalWidth > 0))).toBe(true);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('promociones.png'), fullPage: true });
  await card.getByRole('button', { name: 'Enviar por correo' }).click();
  await dialog.getByRole('button', { name: 'Revisar correo y destinatarios' }).click();
  await expect(dialog.getByText('Modo de pruebas: no se enviarán correos reales.')).toBeVisible();
  await expect(page.frameLocator('iframe').getByRole('heading', {name, exact:true})).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('correo-previo.png'), fullPage: true });
  await dialog.getByRole('button', { name: 'Confirmar prueba local' }).click();
  await expect(dialog).not.toBeVisible();
  await page.getByRole('button', { name: 'Historial de campañas' }).click();
  const campaign = dialog.getByRole('article').filter({ has: page.getByRole('heading', { name, exact: true }) });
  await expect(campaign.getByText(/Finalizada/)).toBeVisible({ timeout: 20000 });
  await campaign.getByRole('button', { name: 'Ver destinatarios y correos' }).click();
  const row = dialog.getByRole('row').filter({ hasText: email });
  await expect(row).toContainText('Prueba local');
  await row.getByRole('button', { name: 'Ver correo' }).click();
  const link = page.frameLocator('iframe').getByRole('link', { name: 'Dejar de recibir promociones' });
  const unsubscribeUrl = await link.getAttribute('href');
  expect(unsubscribeUrl).toContain('/baja#token=');
  await page.goto(unsubscribeUrl!);
  await page.getByRole('button', { name: 'Dejar de recibir promociones' }).click();
  await expect(page.getByRole('status')).toContainText('Ya no recibirás promociones');
  await page.goto('/admin/promociones');
  await page.getByLabel('Buscar promociones').fill(unique);
  await card.getByRole('button', { name: 'Preparar nuevo envío' }).click();
  await dialog.getByLabel('Programar para más tarde').check();
  await dialog.getByLabel('Fecha y hora de envío (Lima)').fill(local(Date.now() + 86400000));
  await dialog.getByRole('button', { name: 'Revisar correo y destinatarios' }).click();
  await dialog.getByRole('button', { name: 'Confirmar programación' }).click();
  await expect(dialog).not.toBeVisible();
  await card.getByRole('switch').click();
  await expect(card.getByRole('switch')).toHaveAttribute('aria-checked', 'false');
  await card.getByRole('button', { name: 'Eliminar', exact: true }).click();
  await expect(dialog.getByRole('heading', { name: 'Eliminar promoción', exact: true })).toBeVisible();
  await expect(dialog.getByText(`Código: E2E-${unique.toUpperCase()}`)).toBeVisible();
  await dialog.getByRole('button', { name: 'Cancelar', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  await expect(card).toBeVisible();
  await card.getByRole('button', { name: 'Eliminar', exact: true }).click();
  await page.screenshot({ path: testInfo.outputPath('eliminar-promocion.png'), fullPage: true });
  await dialog.getByRole('button', { name: 'Confirmar eliminación' }).click();
  await expect(dialog).not.toBeVisible();
  await expect(card).toHaveCount(0);
  await page.reload();
  await page.getByLabel('Buscar promociones').fill(unique);
  await expect(page.getByRole('heading', { name: 'No hay promociones para mostrar' })).toBeVisible();
  await page.getByRole('button', { name: 'Historial de campañas' }).click();
  const historyCards = dialog.getByRole('article').filter({ has: page.getByRole('heading', { name, exact: true }) });
  await expect(historyCards).toHaveCount(2);
  await expect(historyCards.filter({ hasText: 'Campaña cancelada porque se eliminó la promoción.' })).toHaveCount(1);
});
