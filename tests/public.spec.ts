import { test, expect } from '@playwright/test';
import { randomBytes, randomInt } from 'node:crypto';

test('public homepage, navigation and real customer registration', async ({ page }, testInfo) => {
  await page.route('**/api/v1/auth/me', route => route.fulfill({ status: 503, body: '{}' }));
  await page.goto('/');
  await expect(page.getByRole('heading', { level: 1, name: 'El Tumi', exact: true })).toBeVisible();
  await page.evaluate(() => document.fonts.ready);
  if (testInfo.project.name === 'mobile') await page.getByRole('button', { name: 'Abrir navegación' }).click();
  await page.getByRole('navigation', { name: 'Navegación del restaurante' }).getByRole('link', { name: 'Regístrate', exact: true }).click();
  const form = page.getByRole('form', { name: 'Registro de clientes' });
  await expect(form).toBeVisible();
  await form.getByLabel('Nombre', { exact: true }).fill('Cliente E2E');
  const email = `${randomBytes(8).toString('hex')}@e2e.example.test`;
  const phone = `9${randomInt(10000000, 99999999)}`;
  await form.getByLabel('Correo electrónico', { exact: true }).fill(email);
  await form.getByLabel('Número de teléfono', { exact: true }).fill('123');
  await form.getByRole('button', { name: 'Quiero recibir promociones' }).click();
  await expect(form.getByRole('checkbox')).not.toBeChecked();
  await form.getByRole('checkbox').check();
  await form.getByRole('button', { name: 'Quiero recibir promociones' }).click();
  await expect(page.getByText('Ingresa un celular peruano de 9 dígitos.')).toBeVisible();
  await form.getByLabel('Número de teléfono', { exact: true }).fill(phone);
  await form.getByRole('button', { name: 'Quiero recibir promociones' }).click();
  await expect(form.getByRole('status')).toContainText('Ya estás registrado');
  await form.getByRole('button', { name: 'Registrar a otra persona' }).click();
  await form.getByLabel('Nombre', { exact: true }).fill('Otro nombre');
  await form.getByLabel('Correo electrónico', { exact: true }).fill(email);
  await form.getByLabel('Número de teléfono', { exact: true }).fill(`+51 ${phone}`);
  await form.getByRole('checkbox').check();
  await form.getByRole('button', { name: 'Quiero recibir promociones' }).click();
  await expect(form.getByRole('alert')).toContainText('ya está registrado');
  await page.getByRole('button', { name: 'Entradas', exact: true }).click();
  await expect(page.getByText('Pronto publicaremos los platos de esta categoría.')).toBeVisible();
  await page.getByRole('button', { name: 'Platos Principales', exact: true }).click();
  await page.getByRole('button', { name: 'Pausar promociones' }).click();
  await page.getByRole('button', { name: 'Ver promoción 2' }).click();
  await expect(page.getByRole('heading', { name: 'Sabor de los Andes' })).toBeVisible();
  await page.getByRole('button', { name: 'Ver promoción 1' }).click();
  await page.getByRole('button', { name: 'Política de Privacidad' }).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.getByRole('button', { name: 'Cerrar', exact: true }).click();
  // Load lazy assets throughout the page before checking image slots and the screenshot.
  await page.evaluate(async () => { for (const img of document.images) img.loading = 'eager'; await Promise.all([...document.images].map(img => img.decode().catch(() => {}))); });
  const images = await page.locator('img').evaluateAll(nodes => nodes.filter(node => node.getClientRects().length > 0).every(node => (node as HTMLImageElement).naturalWidth > 0));
  expect(images).toBe(true);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: testInfo.outputPath('public-home.png'), fullPage: true });
  await page.unroute('**/api/v1/auth/me');
  await page.getByRole('link', { name: 'Acceso administrativo' }).click();
  await expect(page.getByRole('heading', { name: 'Panel de Administración' })).toBeVisible();
});
