import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
test('administrative access, persistence, navigation and logout', async ({ page }, testInfo) => {
  const credentials = JSON.parse(readFileSync('.local/e2e-admin.json', 'utf8'));
  await page.goto('/admin/clientes');
  await expect(page.getByRole('heading', { name: 'Panel de Administración' })).toBeVisible();
  await page.evaluate(() => document.fonts.ready);
  await expect.poll(() => page.locator('img').evaluateAll(images => images.every(image => (image as HTMLImageElement).complete && (image as HTMLImageElement).naturalWidth > 0))).toBe(true);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('login.png'), fullPage: true });
  await page.getByLabel('Correo electrónico', { exact: true }).fill(credentials.email);
  await page.getByLabel('Contraseña de Acceso', { exact: true }).fill('incorrecta');
  await page.getByRole('button', { name: 'Iniciar Sesión', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('incorrectos');
  await page.getByLabel('Contraseña de Acceso', { exact: true }).fill(credentials.password);
  await page.getByRole('button', { name: 'Mostrar contraseña' }).click();
  await expect(page.locator('#password')).toHaveAttribute('type', 'text');
  await page.getByRole('button', { name: 'Ocultar contraseña' }).click();
  await page.getByLabel('Mantener sesión iniciada').check();
  await page.getByRole('button', { name: 'Iniciar Sesión', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Dashboard General' })).toBeVisible();
  await page.reload();
  await expect(page.getByText('Sesión iniciada', { exact: true })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('panel.png'), fullPage: true });
  if (testInfo.project.name === 'mobile') await page.getByRole('button', { name: 'Abrir menú' }).click();
  await page.getByRole('navigation').getByRole('link', { name: 'Clientes (CRM)' }).click();
  await expect(page.getByRole('heading', { name: 'Clientes (CRM)' })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  if (testInfo.project.name === 'mobile') await page.getByRole('button', { name: 'Abrir menú' }).click();
  await page.getByRole('button', { name: 'Cerrar Sesión' }).click();
  await expect(page.getByRole('heading', { name: 'Panel de Administración' })).toBeVisible();
  await page.getByRole('link', { name: '¿Olvidó su contraseña?' }).click();
  await page.getByLabel('Correo electrónico', { exact: true }).fill('unknown@example.test');
  await page.getByRole('button', { name: 'Enviar enlace' }).click();
  await expect(page.getByRole('status')).toContainText('Si el correo corresponde');
});
